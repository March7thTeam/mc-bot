const all = [...TIPS, ...BUILD_TIPS]
// 模组扩展启用后接进来（进服拿到注册表才知道装了哪些模组）
let mods = null, facts = null
function useMods(source) { mods = source }
function useVersion(source) { facts = source }

// 按文本里出现的关键词挑最相关的几条
function relevantTips(text, max = 4) {
  const t = String(text || '').toLowerCase()
  return [...all, ...(mods?.tips() || [])].filter((tip) => !facts ||
    ((!tip.since || compareRelease(facts.release, tip.since) >= 0) && (!tip.until || compareRelease(facts.release, tip.until) <= 0))).map((tip) => ({ tip, hits: tip.keys.filter((k) => t.includes(k.toLowerCase())).length }))
    .filter((x) => x.hits > 0).sort((a, b) => b.hits - a.hits).slice(0, max).map((x) => x.tip.text)
}

// 模组物品名 → 它所属模组扩展的说明（按命名空间匹配）
function modTipFor(fullName) {
  return mods?.summaryFor(fullName) || null
}

module.exports = { relevantTips, modTipFor, useMods, useVersion, TIPS }
